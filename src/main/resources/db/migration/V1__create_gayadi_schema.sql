    id                  BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    notification_type   VARCHAR(40)  NOT NULL,
    title               VARCHAR(200) NOT NULL,
    content             VARCHAR(1000) NOT NULL,
    trip_id             BIGINT,
    invitation_id       BIGINT,
    plan_id             BIGINT,
    plan_item_id        BIGINT,
    route_id            BIGINT,
    event_id            BIGINT,
    proposal_id         BIGINT,
    is_read             BOOLEAN      NOT NULL DEFAULT FALSE,
    read_at             Timestamp,
    sent_at             Timestamp,
    created_at          Timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notif_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_notif_trip FOREIGN KEY (trip_id) REFERENCES trips (id) ON DELETE CASCADE,
    CONSTRAINT fk_notif_invitation FOREIGN KEY (invitation_id) REFERENCES travel_invitations (id),
    CONSTRAINT fk_notif_plan FOREIGN KEY (plan_id) REFERENCES travel_plans (id),
    CONSTRAINT fk_notif_plan_item FOREIGN KEY (plan_item_id) REFERENCES travel_plan_items (id),
    CONSTRAINT fk_notif_route FOREIGN KEY (route_id) REFERENCES travel_routes (id),
    CONSTRAINT fk_notif_event FOREIGN KEY (event_id) REFERENCES event_observations (id),
    CONSTRAINT fk_notif_proposal FOREIGN KEY (proposal_id) REFERENCES ai_schedule_change_proposals (id)
);

-- 19. 사용자 기기
